from __future__ import annotations

import json
from unittest.mock import MagicMock, patch
import pytest

from app.gemini import GeminiKeyPool, is_rate_limit_or_quota_error, generate_plan


class DummyRateLimitError(Exception):
    def __init__(self, code: int = 429, message: str = "Resource has been exhausted (check quota)."):
        self.code = code
        self.message = message
        self.status = "RESOURCE_EXHAUSTED"
        super().__init__(f"{code} {self.status}: {message}")


def test_key_discovery_and_masking(monkeypatch):
    pool = GeminiKeyPool()
    for i in range(3, 15):
        monkeypatch.delenv(f"GEMINI_API_KEY_{i}", raising=False)
    monkeypatch.setenv("GEMINI_API_KEY_1", "key-alpha-1234567890")
    monkeypatch.setenv("GEMINI_API_KEY_2", "key-beta-9876543210")
    monkeypatch.setenv("GEMINI_API_KEYS", "key-gamma-1111111111, key-delta-2222222222")
    monkeypatch.setenv("GEMINI_API_KEY", "key-epsilon-3333333333")

    keys = pool.get_configured_keys()
    assert len(keys) == 5
    assert keys[0] == "key-gamma-1111111111"
    assert keys[1] == "key-delta-2222222222"
    assert keys[2] == "key-alpha-1234567890"
    assert keys[3] == "key-beta-9876543210"
    assert keys[4] == "key-epsilon-3333333333"

    masked = pool.mask_key("key-alpha-1234567890")
    assert masked.startswith("key-al")
    assert masked.endswith("7890")
    assert "..." in masked


def test_rate_limit_detection():
    err1 = DummyRateLimitError(429)
    assert is_rate_limit_or_quota_error(err1) is True

    err2 = Exception("Quota exceeded for quota metric 'GenerateContent'")
    assert is_rate_limit_or_quota_error(err2) is True

    err3 = Exception("Rate limit reached for requests per minute")
    assert is_rate_limit_or_quota_error(err3) is True

    err4 = ValueError("Invalid prompt format")
    assert is_rate_limit_or_quota_error(err4) is False


def test_instant_failover_to_next_key(monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY_1", "test-key-primary-12345")
    monkeypatch.setenv("GEMINI_API_KEY_2", "test-key-backup-67890")
    monkeypatch.delenv("GEMINI_API_KEYS", raising=False)
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)

    call_records: list[str] = []

    def mock_genai_client(api_key: str):
        client = MagicMock()
        def mock_generate_content(*args, **kwargs):
            call_records.append(api_key)
            if api_key == "test-key-primary-12345":
                # Key 1 hits quota limit 429
                raise DummyRateLimitError(429, "Quota exhausted on primary key")
            # Key 2 succeeds!
            mock_resp = MagicMock()
            mock_resp.text = json.dumps({
                "summary": "Plan generated by backup key",
                "steps": ["Step 1 from backup key", "Step 2 from backup key"],
                "approval_reason": "Automated verification"
            })
            return mock_resp

        client.models.generate_content.side_effect = mock_generate_content
        return client

    with patch("app.gemini.genai.Client", side_effect=mock_genai_client):
        result = generate_plan(
            objective="Explore Kandy cultural triangle",
            agent_names=["TripPlannerAgent", "BudgetAgent"],
            destination="Kandy",
        )

        assert result is not None
        assert result["summary"] == "Plan generated by backup key"
        assert len(result["steps"]) == 2
        # Verify both keys were attempted: primary first, then backup
        assert len(call_records) == 2
        assert call_records[0] == "test-key-primary-12345"
        assert call_records[1] == "test-key-backup-67890"


def test_graceful_deterministic_fallback_when_all_fail(monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY_1", "test-key-1-12345")
    monkeypatch.setenv("GEMINI_API_KEY_2", "test-key-2-67890")
    monkeypatch.delenv("GEMINI_API_KEYS", raising=False)
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    monkeypatch.setenv("AI_REQUIRE_GEMINI", "false")

    def mock_genai_client(api_key: str):
        client = MagicMock()
        client.models.generate_content.side_effect = DummyRateLimitError(429, "All keys exhausted")
        return client

    with patch("app.gemini.genai.Client", side_effect=mock_genai_client):
        result = generate_plan(
            objective="Group hike to Ella Rock",
            agent_names=["TripPlannerAgent"],
            destination="Ella",
        )

        assert result is not None
        # Safe fallback was returned
        assert "Deterministic coordinated plan" in result["summary"]
        assert len(result["steps"]) > 0
        assert "approval_reason" in result
